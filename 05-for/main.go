//for = para 
//estructura simple  for inicio ; condicion , incremento
package main
import (
	"fmt"
)

func main(){
	fmt.Println("----------FOR COMUM")
	//para revisar un servidor 
	for numeroActual := 1; numeroActual <= 5; numeroActual++{
		fmt.Println(numeroActual)
	}

	for servidor := 1; servidor <= 5; servidor++{
		fmt.Println(servidor)
	}
	


}